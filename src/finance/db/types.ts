/**
 * 가계부 도메인 엔티티 — spec-finance-v0.2.md §3.2
 *
 * 금액은 전부 원 단위 정수다(§2.4). 부동소수 오차를 원천 차단한다.
 * 날짜는 'YYYY-MM-DD' 문자열, 타임스탬프는 epoch ms(number)로 운동 쪽 규약과 같다.
 */

export type TxType = 'EXPENSE' | 'SAVING' | 'TRANSFER' | 'INCOME'

export type AssetKind =
  | 'SAVINGS'
  | 'INVESTMENT'
  | 'PENSION'
  | 'CASH'
  | 'DEPOSIT'

export interface Transaction {
  id: string
  /** "2026-10-03" */
  date: string
  /** "2026-10" — 저장 시 계산하고, 급여일이 바뀌면 재계산한다(§2.1) */
  cycleKey: string
  type: TxType
  categoryId: string
  amount: number
  memo?: string
  isFixed: boolean
  isAutoGenerated: boolean
  /** 어느 고정비에서 나왔는지. 중복 생성 방지의 실제 키다(§5.6) */
  fixedCostId?: string
}

/** 카테고리를 묶는 상위 분류. '차량' 아래 '차량 할부 원금'처럼 쓴다. */
export interface Group {
  id: string
  name: string
  sortOrder: number
}

export interface Category {
  id: string
  name: string
  groupId: string
  type: TxType
  /** 월 예산 */
  budget: number
  isFixed: boolean
  sortOrder: number
  isArchived: boolean
  /**
   * 이 카테고리의 거래가 쌓는 자산 — spec-finance-v0.12 §5.7
   *
   * 거래마다 자산을 고르게 하면 입력이 번거로워진다. 카테고리 단위로 묶고,
   * 세분이 필요하면 카테고리를 쪼갠다('투자' → '투자-ETF', '투자-연금').
   */
  assetId?: string
  /** 이 카테고리의 거래가 갚는 부채. assetId와 동시에 쓰지 않는다 */
  debtId?: string
}

/** 매월 반복되는 고정비 — 사이클에 반영하면 Transaction이 된다 */
export interface FixedCost {
  id: string
  categoryId: string
  amount: number
  dayOfMonth: number
  isActive: boolean
  /** "2026-10" */
  startCycle: string
  endCycle?: string
  note?: string
  /**
   * 이 고정비가 갚는 부채. 사이클에 반영할 때 잔액을 그만큼 줄인다.
   * 매달 수동으로 잔액을 고치지 않아도 되게 하려는 연결이다.
   */
  linkedDebtId?: string
  /** 이 고정비가 쌓는 자산. 반영할 때 잔액을 그만큼 늘린다. */
  linkedAssetId?: string
}

export interface Asset {
  id: string
  name: string
  kind: AssetKind
  balance: number
  /** 수익률 계산용 */
  principal?: number
  updatedAt: number
  /** 목표 시점에 현금화 가능 여부 */
  isLiquidByTarget: boolean
  note?: string
  /**
   * 순자산에 포함하는가 — spec-finance-v0.12 §5.8
   *
   * 보증금처럼 돌려받긴 하지만 "모으고 있는 돈"이 아닌 자산을 뺀다.
   * undefined는 `kind !== 'DEPOSIT'`으로 읽는다 — 기존 데이터에
   * 마이그레이션을 쓰지 않기 위한 지연 기본값이다.
   */
  countsInNetWorth?: boolean
  /**
   * 거래 반영 기준일 'YYYY-MM-DD' — §5.7
   *
   * `balance`가 이 날짜 기준이라는 뜻이고, **이 날짜보다 뒤의** 연결된
   * 거래만 더한다. 잔액을 직접 입력하면 그 날짜로 갱신되므로 이중 계산이 없다.
   */
  reflectFrom?: string
}

export interface Debt {
  id: string
  name: string
  balance: number
  /** 거래 반영 기준일 'YYYY-MM-DD' — Asset.reflectFrom과 같은 규약(§5.7) */
  reflectFrom?: string
  /** 학자금처럼 원금을 모르는 경우가 있다(§4.6) */
  originalAmount?: number
  /** 연 %. 〃 */
  interestRate?: number
  monthlyPayment: number
  monthlyPrincipal: number
  monthlyInterest: number
  /** "2030-10" */
  expectedPayoff?: string
  countsInDTI: boolean
}

export interface Goal {
  id: string
  name: string
  /** "2029-03" */
  targetDate: string
  targetAmount: number
  note?: string
}

/** 순자산 스냅샷 */
export interface NetWorthSnapshot {
  /** 기본키. 사이클당 한 건이라 다시 찍어도 덮어쓴다 */
  cycleKey: string
  totalAssets: number
  totalDebts: number
  netWorth: number
  /**
   * 순자산에서 제외된 자산 합계 (보증금 등) — v0.12에서 추가.
   *
   * **없는 행은 옛 공식으로 계산된 것이다.** v0.12 이전 스냅샷은
   * 보증금을 순자산에 포함해 찍혀 있어, 추이 그래프에 한 번 단절이 생긴다.
   * 과거 잔액이 어디에도 없으므로 다시 계산할 수 없다(§5.4, §5.8).
   */
  excludedAssets?: number
  /** 실제로 기록한 시각 */
  capturedAt: number
  /**
   * 이 금액이 어느 날 기준인가 ('YYYY-MM-DD').
   * 사이클이 끝나는 날에 맞춰 자산을 갱신하기 어렵다. 며칠 지나 입력하더라도
   * 기준일을 남겨 두면 추이 그래프를 읽을 때 근거가 된다.
   */
  asOf?: string
}

/**
 * 사이클 총예산 — 카테고리 예산 합계와 별도로 잡는다.
 *
 * 카테고리별 예산은 항목마다 얼마를 쓸지의 계획이고, 사이클 총예산은
 * "이번 달 전체로 얼마까지"라는 상한이다. 둘은 다를 수 있다.
 * 설정하지 않은 사이클은 카테고리 합계를 쓴다.
 */
export interface CycleBudget {
  /** 기본키. "2026-10" */
  cycleKey: string
  amount: number
}

export interface Deduction {
  label: string
  amount: number
  /**
   * 부채 원금 상환처럼 순자산이 되는 공제인가.
   * 저축률의 분자와 총소득 분모를 여기서 만든다(§2.3.1).
   */
  isTransfer: boolean
  /**
   * 이 공제가 갚는 부채. 급여에서 바로 빠지므로 Transaction은 만들지 않지만
   * (§2.3.1 이중 계산 방지) 부채 잔액은 줄어야 한다.
   */
  linkedDebtId?: string
}

/**
 * 원천 차감분을 어느 사이클에 이미 적용했는지.
 *
 * 고정비는 Transaction 존재 여부로 중복을 막지만(§5.6), 원천 차감은
 * Transaction을 만들지 않아 판단 근거가 없다. 그래서 따로 기록한다.
 */
export interface AppliedDeduction {
  /** 기본키. `${cycleKey}:${label}` */
  id: string
  cycleKey: string
  label: string
  debtId: string
  amount: number
  appliedAt: number
}

/**
 * 사이클별 카테고리 예산 스냅샷.
 *
 * Category.budget은 값이 하나뿐이라 매달 예산을 바꾸면 과거 사이클의
 * "예산 대비 실적"까지 새 예산으로 평가된다. 사이클마다 그때 정한 값을
 * 남겨 두면 과거 리포트가 변하지 않는다.
 */
export interface CycleCategoryBudget {
  /** 기본키. `${cycleKey}:${categoryId}` */
  id: string
  cycleKey: string
  categoryId: string
  amount: number
}

/** 소득 설정 — id가 'default'인 단일 레코드 */
export interface IncomeSetting {
  id: 'default'
  grossPay: number
  netPay: number
  /** 급여일. 기본 25. 상수가 아니라 설정값이다(§2.1) */
  payday: number
  deductions: Deduction[]
}
