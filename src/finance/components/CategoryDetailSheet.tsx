import { useLiveQuery } from 'dexie-react-hooks'
import { Sheet } from '../../components/Sheet'
import { listTransactionsByCategory } from '../db/transactions'
import { formatWon } from '../lib/money'

/**
 * 카테고리 세부 내역 — spec-finance-v0.12 §5.1.1
 *
 * 대시보드는 "식비 42만원"까지만 알려 준다. 예산을 넘겼을 때 바로 묻게 되는
 * 것은 "언제 뭘 썼길래"이고, 그걸 보려면 입력 화면으로 가서 주를 넘겨가며
 * 찾아야 했다. 누른 자리에서 바로 펼친다.
 *
 * 수정·삭제를 두지 않는 이유 — 조회 중에 지우면 위의 합계가 흔들리고,
 * 실수로 지웠을 때 되돌릴 방법이 없다. 변경은 입력 화면에서 한다.
 */
export function CategoryDetailSheet({
  cycleKey,
  categoryId,
  name,
  spent,
  budget,
  onClose,
}: {
  cycleKey: string
  categoryId: string
  name: string
  spent: number
  budget: number
  onClose: () => void
}) {
  const rows = useLiveQuery(
    () => listTransactionsByCategory(cycleKey, categoryId),
    [cycleKey, categoryId],
  )

  return (
    <Sheet title={name} onClose={onClose}>
      <div className="flex flex-col gap-3">
        <div className="flex items-baseline justify-between rounded-xl bg-zinc-50 p-3 ring-1 ring-zinc-200">
          <span className="text-[13px] text-zinc-500">{cycleKey} 합계</span>
          <span className="text-[17px] font-semibold tabular-nums text-zinc-900">
            {formatWon(spent)}
            {budget > 0 && (
              <span className="text-[13px] font-normal text-zinc-400">
                {' '}
                / {formatWon(budget)}
              </span>
            )}
          </span>
        </div>

        {rows === undefined ? null : rows.length === 0 ? (
          <p className="rounded-xl bg-white px-3 py-6 text-center text-[13px] text-zinc-400 ring-1 ring-zinc-200">
            이 사이클에는 입력이 없습니다
          </p>
        ) : (
          <ul className="flex flex-col gap-1.5">
            {rows.map((tx) => (
              <li
                key={tx.id}
                className="flex items-center gap-2 rounded-xl bg-white p-3 ring-1 ring-zinc-200"
              >
                <div className="min-w-0 flex-1">
                  <p className="text-[14px] tabular-nums text-zinc-900">
                    {tx.date}
                    {tx.isAutoGenerated && (
                      <span className="ml-1.5 text-[11px] text-zinc-400">
                        고정비
                      </span>
                    )}
                  </p>
                  {tx.memo && (
                    <p className="truncate text-[12px] text-zinc-500">
                      {tx.memo}
                    </p>
                  )}
                </div>
                <span className="shrink-0 text-[15px] font-semibold tabular-nums text-zinc-900">
                  {formatWon(tx.amount)}
                </span>
              </li>
            ))}
          </ul>
        )}

        <p className="text-[11px] leading-relaxed text-zinc-400">
          수정·삭제는 입력 화면에서 합니다. 여기서 지우면 위 합계가 흔들려
          무엇을 보고 있었는지 알기 어려워집니다.
        </p>
      </div>
    </Sheet>
  )
}
