/**
 * 실효 잔액과 순자산 검증 — spec-finance-v0.15 §5.7, §5.8
 *
 * 실행: npm run check:balances
 *
 * 이중 계산은 오류를 내지 않고 숫자만 틀리게 만든다. 화면으로는
 * "좀 많아 보이네" 수준이라 몇 달 뒤에야 발견된다. 그래서 하네스로 못 박는다.
 *
 * 확인하는 불변식:
 *   1. 연결이 없으면 잔액이 그대로다
 *   2. 기준일부터의 거래를 더한다 (당일 포함 — 도입 첫날의 실제 경로)
 *   3. 거래를 지우면 잔액이 자동으로 돌아간다
 *   4. 잔액을 다시 입력하면 기준일이 리셋되어 이중 계산이 없다
 *   5. 부채는 줄고 0 아래로 내려가지 않는다
 *   6. 고정비 연결이 카테고리 연결보다 우선한다
 *   7. 보증금도 기본 포함 (그래프에서만 기본 숨김)
 *   8. 끄면 빠진다 / 8-a 실제 대출 구조에서 이중 계산 함정
 *   9. 기준일이 없으면 반영하지 않는다 (옛 백업 복원 시 폭주 방지)
 *  10. 현금 자동 연결 — 수입은 +, 지출·저축·이체는 −
 *  11. 현금 자산이 0개·2개 이상이면 자동 연결이 꺼진다
 *  12. 저축은 현금에서 빠지고 적금에 들어간다 (순자산 불변)
 *  13. 원천 공제가 부채에 반영되고, 현금은 건드리지 않는다
 *  14. 급여 거래를 지우면 공제도 함께 지워져 부채가 돌아온다
 *  15. 갚은 원금을 순자산에 더하는 옵션
 *  16. 자산·부채를 지우면 끊긴 연결도 정리된다
 *  17. 자산 − 부채 = 순자산 (상환 지분 포함) + 그래프 조각에도 나온다
 */
import 'fake-indexeddb/auto'

let failures = 0

function check(label: string, actual: unknown, expected: unknown): void {
  const a = JSON.stringify(actual)
  const e = JSON.stringify(expected)
  if (a === e) {
    console.log(`  ok   ${label}`)
  } else {
    failures += 1
    console.log(`  FAIL ${label}\n         기대: ${e}\n         실제: ${a}`)
  }
}

async function main(): Promise<void> {
  const { financeDb } = await import('../src/finance/db/db')
  const { loadBalances } = await import('../src/finance/db/balances')
  const { computeNetWorth, countsInNetWorth, hiddenFromChart } = await import(
    '../src/finance/lib/netWorth'
  )
  const { saveAsset } = await import('../src/finance/db/assets')
  const { applySalaryDeductions } = await import('../src/finance/db/salary')

  await financeDb.open()

  const reset = async () => {
    await financeDb.assets.clear()
    await financeDb.debts.clear()
    await financeDb.categories.clear()
    await financeDb.transactions.clear()
    await financeDb.fixedCosts.clear()
    await financeDb.appliedDeductions.clear()
    await financeDb.incomeSettings.clear()
  }

  const addCash = (over: Record<string, unknown> = {}) =>
    financeDb.assets.add({
      id: 'cash',
      name: '통장',
      kind: 'CASH',
      balance: 2_000_000,
      updatedAt: 1,
      isLiquidByTarget: true,
      reflectFrom: '2026-10-01',
      ...over,
    } as never)

  const addAsset = (over: Record<string, unknown> = {}) =>
    financeDb.assets.add({
      id: 'a1',
      name: '적금',
      kind: 'SAVINGS',
      balance: 1_000_000,
      updatedAt: 1,
      isLiquidByTarget: true,
      reflectFrom: '2026-10-01',
      ...over,
    } as never)

  const addCategory = (over: Record<string, unknown> = {}) =>
    financeDb.categories.add({
      id: 'c1',
      name: '예적금',
      groupId: 'g1',
      type: 'SAVING',
      budget: 0,
      isFixed: false,
      sortOrder: 0,
      isArchived: false,
      ...over,
    } as never)

  const addTx = (id: string, date: string, amount: number, over = {}) =>
    financeDb.transactions.add({
      id,
      date,
      cycleKey: date.slice(0, 7),
      type: 'SAVING',
      categoryId: 'c1',
      amount,
      isFixed: false,
      isAutoGenerated: false,
      ...over,
    } as never)

  console.log('\n[1] 연결이 없으면 잔액 그대로')
  await reset()
  await addAsset()
  await addCategory() // assetId 없음
  await addTx('t1', '2026-10-10', 500_000)
  let balances = await loadBalances()
  check('잔액 변화 없음', balances.assets[0].balance, 1_000_000)
  check('반영액 0', balances.assets[0].reflected, 0)

  console.log('\n[2] 기준일부터의 거래를 더한다 (이상 비교)')
  await reset()
  await addAsset({ reflectFrom: '2026-10-10' })
  await addCategory({ assetId: 'a1' })
  await addTx('before', '2026-10-05', 100_000) // 기준일 이전 — 제외
  await addTx('sameday', '2026-10-10', 200_000) // 기준일 당일 — 포함
  await addTx('after', '2026-10-15', 300_000) // 이후 — 포함
  balances = await loadBalances()
  check('기준일 이전은 제외', balances.assets[0].reflected, 500_000)
  check('잔액 = 원금 + 반영', balances.assets[0].balance, 1_500_000)

  /**
   * 도입 첫날의 실제 경로 — 이게 깨지면 "연결했는데 아무 일도 안 일어난다"가 된다.
   *
   * 마이그레이션이 기준일을 오늘로 박으므로, 카테고리를 연결하고 그날 거래를
   * 넣는 것이 가장 흔한 첫 경험이다. 초과 비교였을 때 이 경우가 조용히
   * 반영되지 않았다.
   */
  console.log('\n[2-a] 기준일 당일에 넣은 거래가 반영되는가')
  await reset()
  const todayKey = new Date().toISOString().slice(0, 10)
  await addAsset({ reflectFrom: todayKey })
  await addCategory({ assetId: 'a1' })
  await addTx('t-today', todayKey, 400_000)
  balances = await loadBalances()
  check('연결 당일 거래 반영', balances.assets[0].reflected, 400_000)
  check('잔액 증가', balances.assets[0].balance, 1_400_000)

  console.log('\n[3] 거래를 지우면 자동으로 돌아간다')
  await financeDb.transactions.delete('t-today')
  balances = await loadBalances()
  check('삭제 후 반영액 0', balances.assets[0].reflected, 0)
  check('삭제 후 잔액 복귀', balances.assets[0].balance, 1_000_000)

  console.log('\n[4] 잔액 재입력이 기준일을 리셋한다 — 이중 계산 방지')
  await reset()
  await addAsset({ reflectFrom: '2026-10-01' })
  await addCategory({ assetId: 'a1' })
  await addTx('t1', '2026-10-15', 500_000)
  balances = await loadBalances()
  check('반영 전 잔액', balances.assets[0].balance, 1_500_000)

  // 화면이 보여 준 1,500,000을 그대로 저장한다 (오늘이 기준일이 된다)
  const today = new Date()
  const todayStr = `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(2, '0')}-${String(today.getDate()).padStart(2, '0')}`
  await saveAsset(
    {
      name: '적금',
      kind: 'SAVINGS',
      balance: 1_500_000,
      isLiquidByTarget: true,
    },
    'a1',
  )
  const saved = await financeDb.assets.get('a1')
  check('기준일이 오늘로 리셋', saved?.reflectFrom, todayStr)
  balances = await loadBalances()
  check('재입력 후 이중 계산 없음', balances.assets[0].balance, 1_500_000)
  check('재입력 후 반영액 0', balances.assets[0].reflected, 0)

  /**
   * 이상 비교의 알려진 대가 — 사고가 아니라 선택이다.
   *
   * 은행 앱에서 본 잔액(오늘 거래가 이미 포함된 금액)을 그대로 적으면
   * 그날 거래가 두 번 센다. 이 경우를 막으려 초과 비교를 썼다가 "연결했는데
   * 아무 일도 안 일어난다"는 더 흔하고 더 나쁜 증상을 만들었다.
   *
   * 테스트로 남겨 두는 이유 — 누군가 "이중 계산이네" 하고 초과 비교로
   * 되돌리는 것을 막기 위해서다. 그 선택의 결과가 무엇인지 여기 적혀 있다.
   */
  console.log('\n[4-a] 알려진 대가: 기준일 당일 거래는 재입력 시 두 번 센다')
  await reset()
  const t2 = new Date().toISOString().slice(0, 10)
  await addAsset({ balance: 1_000_000, reflectFrom: t2 })
  await addCategory({ assetId: 'a1' })
  await addTx('same', t2, 300_000)
  balances = await loadBalances()
  check('반영 후 1,300,000', balances.assets[0].balance, 1_300_000)
  // 화면이 보여 준 1,300,000을 그대로 저장한다 (기준일도 오늘)
  await saveAsset(
    { name: '적금', kind: 'SAVINGS', balance: 1_300_000, isLiquidByTarget: true },
    'a1',
  )
  balances = await loadBalances()
  check(
    '당일 거래가 다시 더해진다 (문서화된 동작)',
    balances.assets[0].balance,
    1_600_000,
  )
  check('반영액이 보이므로 확인 가능', balances.assets[0].reflected, 300_000)

  console.log('\n[5] 부채는 줄고 0 아래로 안 내려간다')
  await reset()
  await financeDb.debts.add({
    id: 'd1',
    name: '회사대출',
    balance: 1_000_000,
    monthlyPayment: 0,
    monthlyPrincipal: 0,
    monthlyInterest: 0,
    countsInDTI: true,
    reflectFrom: '2026-10-01',
  } as never)
  await addCategory({ debtId: 'd1', type: 'TRANSFER' })
  await addTx('p1', '2026-10-15', 300_000, { type: 'TRANSFER' })
  balances = await loadBalances()
  check('상환 반영', balances.debts[0].reflected, 300_000)
  check('잔액 감소', balances.debts[0].balance, 700_000)

  await addTx('p2', '2026-10-20', 900_000, { type: 'TRANSFER' })
  balances = await loadBalances()
  check('과다 상환도 0에서 멈춤', balances.debts[0].balance, 0)

  console.log('\n[6] 고정비 연결이 카테고리 연결보다 우선')
  await reset()
  await addAsset({ id: 'a1', name: '청약', reflectFrom: '2026-10-01' })
  await financeDb.assets.add({
    id: 'a2',
    name: '적금',
    kind: 'SAVINGS',
    balance: 0,
    updatedAt: 1,
    isLiquidByTarget: true,
    reflectFrom: '2026-10-01',
  } as never)
  await addCategory({ assetId: 'a1' })
  await financeDb.fixedCosts.add({
    id: 'f1',
    categoryId: 'c1',
    amount: 100_000,
    dayOfMonth: 25,
    isActive: true,
    startCycle: '2026-10',
    linkedAssetId: 'a2',
  } as never)
  await addTx('t1', '2026-10-15', 100_000, { fixedCostId: 'f1' })
  balances = await loadBalances()
  const byId = new Map(balances.assets.map((a) => [a.id, a.reflected]))
  check('고정비가 가리킨 자산에 반영', byId.get('a2'), 100_000)
  check('카테고리 자산에는 반영 안 됨', byId.get('a1'), 0)

  console.log('\n[7] 보증금도 기본적으로 순자산에 포함된다')
  await reset()
  await addAsset({ id: 'a1', name: '적금', kind: 'SAVINGS', balance: 5_000_000 })
  await financeDb.assets.add({
    id: 'a2',
    name: '전세보증금',
    kind: 'DEPOSIT',
    balance: 150_000_000,
    updatedAt: 1,
    isLiquidByTarget: false,
    reflectFrom: '2026-10-01',
  } as never)
  balances = await loadBalances()
  let totals = computeNetWorth(balances.assets, balances.debts)
  // v0.14까지 기본 제외였다. 보증금을 빼면 그걸 사려고 빌린 대출만 남아
  // 순자산이 대출액만큼 음수가 된다 — 수준이 틀어진다.
  check('보증금 포함', totals.netWorth, 155_000_000)
  check('제외 합계 0', totals.excludedAssets, 0)
  check(
    'DEPOSIT 기본 포함',
    countsInNetWorth(balances.assets.find((a) => a.id === 'a2')!),
    true,
  )
  // 그래프에서는 기본 숨김 — 순자산 포함과 별개 결정이다
  check(
    'DEPOSIT 그래프 기본 숨김',
    hiddenFromChart(balances.assets.find((a) => a.id === 'a2')!),
    true,
  )

  console.log('\n[8] 끄면 순자산에서 빠진다')
  await financeDb.assets.update('a2', { countsInNetWorth: false })
  balances = await loadBalances()
  totals = computeNetWorth(balances.assets, balances.debts)
  check('끄면 제외', totals.netWorth, 5_000_000)
  check('제외 합계', totals.excludedAssets, 150_000_000)

  /**
   * 실제 구조 — 보증금 1.5억 = 전세대출 1.2억(이자만) + 사내대출 3천(원리금).
   *
   * "사내대출 원금 상환이 진짜 내 돈이 되는 과정"이라는 직관은 맞다.
   * 그리고 **일반 공식이 이미 그것을 정확히 반영한다** — 부채 잔액이 줄면
   * 그만큼 순자산이 올라간다. 여기에 repaidCountsInNetWorth를 더하면
   * 두 번 센다. 이 테스트가 그 함정을 못 박는다.
   */
  console.log('\n[8-a] 보증금·전세대출·사내대출 구조')
  await reset()
  await financeDb.assets.add({
    id: 'dep',
    name: '전세보증금',
    kind: 'DEPOSIT',
    balance: 150_000_000,
    updatedAt: 1,
    isLiquidByTarget: false,
    reflectFrom: '2026-10-01',
  } as never)
  const addDebt = (id: string, name: string, balance: number, original: number) =>
    financeDb.debts.add({
      id,
      name,
      balance,
      originalAmount: original,
      monthlyPayment: 0,
      monthlyPrincipal: 0,
      monthlyInterest: 0,
      countsInDTI: true,
      reflectFrom: '2026-10-01',
    } as never)
  await addDebt('jeonse', '전세대출', 120_000_000, 120_000_000)
  await addDebt('company', '사내대출', 30_000_000, 30_000_000)

  balances = await loadBalances()
  totals = computeNetWorth(balances.assets, balances.debts)
  check('시작 지분 0', totals.netWorth, 0)

  // 사내대출 원금 500만을 갚았다
  await financeDb.debts.update('company', { balance: 25_000_000 })
  balances = await loadBalances()
  totals = computeNetWorth(balances.assets, balances.debts)
  check('원금 500만 갚으면 지분 500만', totals.netWorth, 5_000_000)

  // ★ 여기에 repaidCountsInNetWorth를 켜면 같은 500만을 또 더한다
  await financeDb.debts.update('company', { repaidCountsInNetWorth: true })
  balances = await loadBalances()
  totals = computeNetWorth(balances.assets, balances.debts)
  check('켜면 두 번 센다 (켜지 말 것)', totals.netWorth, 10_000_000)

  console.log('\n[9] 기준일이 없으면 반영하지 않는다')
  // 옛 백업을 복원하거나 구버전 기기의 스냅샷을 받으면 reflectFrom이 없다.
  // 그때 "전부 더하기"로 읽으면 몇 년치 저축이 한꺼번에 잔액에 더해진다.
  await reset()
  await financeDb.assets.add({
    id: 'a1',
    name: '옛 백업에서 온 자산',
    kind: 'SAVINGS',
    balance: 1_000_000,
    updatedAt: 1,
    isLiquidByTarget: true,
    // reflectFrom 없음
  } as never)
  await addCategory({ assetId: 'a1' })
  await addTx('old1', '2025-01-15', 500_000)
  await addTx('old2', '2025-06-20', 700_000)
  balances = await loadBalances()
  check('기준일 없으면 반영 0', balances.assets[0].reflected, 0)
  check('잔액 그대로', balances.assets[0].balance, 1_000_000)

  console.log('\n[10] 현금 자동 연결 — 부호 방향')
  await reset()
  await addCash()
  await addCategory({ id: 'c-income', type: 'INCOME' })
  await addCategory({ id: 'c-expense', type: 'EXPENSE' })
  await addTx('in', '2026-10-25', 3_000_000, {
    categoryId: 'c-income',
    type: 'INCOME',
  })
  await addTx('out', '2026-10-26', 500_000, {
    categoryId: 'c-expense',
    type: 'EXPENSE',
  })
  balances = await loadBalances()
  let cash = balances.assets.find((a) => a.id === 'cash')!
  check('수입 + / 지출 −', cash.reflected, 2_500_000)
  check('현금 잔액', cash.balance, 4_500_000)

  console.log('\n[11] 현금 자산 개수 조건')
  // 0개 — 자동 연결 없음
  await reset()
  await addAsset({ id: 'a1', kind: 'SAVINGS' })
  await addCategory({ id: 'c-expense', type: 'EXPENSE' })
  await addTx('out', '2026-10-26', 500_000, {
    categoryId: 'c-expense',
    type: 'EXPENSE',
  })
  balances = await loadBalances()
  check('현금 0개 → 반영 없음', balances.assets[0].reflected, 0)

  // 2개 — 어느 쪽인지 알 수 없으므로 꺼진다
  await addCash({ id: 'cash1', name: '통장1' })
  await addCash({ id: 'cash2', name: '통장2' })
  balances = await loadBalances()
  check(
    '현금 2개 → 둘 다 반영 없음',
    balances.assets.filter((a) => a.kind === 'CASH').map((a) => a.reflected),
    [0, 0],
  )

  console.log('\n[12] 저축은 현금에서 적금으로 — 순자산이 변하지 않는다')
  await reset()
  await addCash({ balance: 2_000_000 })
  await addAsset({ id: 'a1', name: '적금', balance: 0, reflectFrom: '2026-10-01' })
  await addCategory({ id: 'c-save', type: 'SAVING', assetId: 'a1' })
  await addTx('s1', '2026-10-20', 700_000, {
    categoryId: 'c-save',
    type: 'SAVING',
  })
  balances = await loadBalances()
  cash = balances.assets.find((a) => a.id === 'cash')!
  const savings = balances.assets.find((a) => a.id === 'a1')!
  check('현금 감소', cash.balance, 1_300_000)
  check('적금 증가', savings.balance, 700_000)
  // 이게 핵심 — 양쪽을 다 움직이지 않으면 순자산이 저축액만큼 부푼다
  check(
    '순자산 불변',
    computeNetWorth(balances.assets, balances.debts).netWorth,
    2_000_000,
  )

  console.log('\n[13] 원천 공제 — 부채는 줄고 현금은 그대로')
  await reset()
  await addCash({ balance: 2_000_000 })
  await financeDb.debts.add({
    id: 'd1',
    name: '사내대출',
    balance: 10_000_000,
    monthlyPayment: 0,
    monthlyPrincipal: 0,
    monthlyInterest: 0,
    countsInDTI: true,
    reflectFrom: '2026-10-01',
  } as never)
  await financeDb.incomeSettings.add({
    id: 'default',
    grossPay: 4_000_000,
    netPay: 3_000_000,
    payday: 25,
    deductions: [
      { label: '사내대출 원금', amount: 400_000, isTransfer: true, linkedDebtId: 'd1' },
    ],
  } as never)
  const applied = await applySalaryDeductions('2026-10', '2026-10-25')
  check('공제 1건 기록', applied, 1)
  balances = await loadBalances()
  check('부채 감소', balances.debts[0].balance, 9_600_000)
  cash = balances.assets.find((a) => a.id === 'cash')!
  // 급여 거래 금액이 실수령액이라 이 돈은 애초에 현금에 들어오지 않았다
  check('현금은 그대로', cash.balance, 2_000_000)

  // 같은 사이클에 다시 부르면 덮어쓴다 (두 번 빠지지 않는다)
  await applySalaryDeductions('2026-10', '2026-10-25', { '사내대출 원금': 500_000 })
  balances = await loadBalances()
  check('재적용은 덮어쓴다', balances.debts[0].balance, 9_500_000)

  console.log('\n[14] 급여 거래를 지우면 공제도 돌아온다')
  // 실제로 막혔던 경로 — 테스트하려고 입력했다 지웠는데 부채가 안 돌아왔다.
  // 공제는 거래가 아니라 appliedDeductions에 따로 남으므로 함께 지워야 한다.
  const { createTransaction, deleteTransaction } = await import(
    '../src/finance/db/transactions'
  )
  await reset()
  await financeDb.debts.add({
    id: 'd1',
    name: '사내대출',
    balance: 10_000_000,
    monthlyPayment: 0,
    monthlyPrincipal: 0,
    monthlyInterest: 0,
    countsInDTI: true,
    reflectFrom: '2026-10-01',
  } as never)
  await financeDb.incomeSettings.add({
    id: 'default',
    grossPay: 4_000_000,
    netPay: 3_000_000,
    payday: 25,
    deductions: [
      { label: '사내대출 원금', amount: 400_000, isTransfer: true, linkedDebtId: 'd1' },
    ],
  } as never)
  await addCategory({ id: 'c-salary', type: 'INCOME', isSalary: true })

  const salaryId = await createTransaction(
    {
      date: '2026-10-25',
      type: 'INCOME',
      categoryId: 'c-salary',
      amount: 3_000_000,
      isFixed: false,
    },
    25,
  )
  await applySalaryDeductions('2026-10', '2026-10-25', {}, salaryId)
  balances = await loadBalances()
  check('공제 반영됨', balances.debts[0].balance, 9_600_000)

  await deleteTransaction(salaryId)
  check('공제 기록도 지워짐', await financeDb.appliedDeductions.count(), 0)
  balances = await loadBalances()
  check('부채가 돌아옴', balances.debts[0].balance, 10_000_000)

  console.log('\n[15] 갚은 원금을 순자산에 더한다')
  await reset()
  // 보증금은 순자산에서 빠지고, 그걸 사려고 빌린 대출은 갚은 만큼 지분이 된다
  await financeDb.assets.add({
    id: 'dep',
    name: '전세보증금',
    kind: 'DEPOSIT',
    balance: 100_000_000,
    updatedAt: 1,
    isLiquidByTarget: false,
    reflectFrom: '2026-10-01',
  } as never)
  await financeDb.debts.add({
    id: 'd1',
    name: '사내대출',
    balance: 90_000_000,
    originalAmount: 100_000_000,
    monthlyPayment: 0,
    monthlyPrincipal: 0,
    monthlyInterest: 0,
    countsInDTI: true,
    reflectFrom: '2026-10-01',
  } as never)
  // 자산을 추적하지 않는 경우를 재현한다 — 그때만 이 옵션이 맞다
  await financeDb.assets.update('dep', { countsInNetWorth: false })
  balances = await loadBalances()
  let totals2 = computeNetWorth(balances.assets, balances.debts)
  check('끈 상태 순자산', totals2.netWorth, -90_000_000)
  check('끈 상태 갚은 원금', totals2.repaidPrincipal, 0)

  await financeDb.debts.update('d1', { repaidCountsInNetWorth: true })
  balances = await loadBalances()
  totals2 = computeNetWorth(balances.assets, balances.debts)
  check('켠 상태 갚은 원금', totals2.repaidPrincipal, 10_000_000)
  check('켠 상태 순자산', totals2.netWorth, -80_000_000)

  // 원금을 모르면 계산할 수 없다 — 0으로 둔다
  await financeDb.debts.update('d1', { originalAmount: undefined })
  balances = await loadBalances()
  totals2 = computeNetWorth(balances.assets, balances.debts)
  check('원금 없으면 0', totals2.repaidPrincipal, 0)

  console.log('\n[16] 삭제가 끊긴 연결을 정리한다')
  const { deleteAsset, deleteDebt } = await import('../src/finance/db/assets')
  await reset()
  await addAsset({ id: 'a1' })
  await financeDb.debts.add({
    id: 'd1',
    name: '대출',
    balance: 1_000_000,
    monthlyPayment: 0,
    monthlyPrincipal: 0,
    monthlyInterest: 0,
    countsInDTI: true,
    reflectFrom: '2026-10-01',
  } as never)
  await addCategory({ id: 'c-save', type: 'SAVING', assetId: 'a1' })
  await addCategory({ id: 'c-pay', type: 'TRANSFER', debtId: 'd1' })
  await financeDb.fixedCosts.add({
    id: 'f1',
    categoryId: 'c-save',
    amount: 100_000,
    dayOfMonth: 25,
    isActive: true,
    startCycle: '2026-10',
    linkedAssetId: 'a1',
    linkedDebtId: 'd1',
  } as never)
  await financeDb.appliedDeductions.add({
    id: '2026-10:원금',
    cycleKey: '2026-10',
    label: '원금',
    debtId: 'd1',
    amount: 100_000,
    appliedAt: 1,
    date: '2026-10-25',
  } as never)

  await deleteAsset('a1')
  check(
    '카테고리의 assetId 정리',
    (await financeDb.categories.get('c-save'))?.assetId,
    undefined,
  )
  check(
    '고정비의 linkedAssetId 정리',
    (await financeDb.fixedCosts.get('f1'))?.linkedAssetId,
    undefined,
  )

  await deleteDebt('d1')
  check(
    '카테고리의 debtId 정리',
    (await financeDb.categories.get('c-pay'))?.debtId,
    undefined,
  )
  check(
    '고정비의 linkedDebtId 정리',
    (await financeDb.fixedCosts.get('f1'))?.linkedDebtId,
    undefined,
  )
  check('고아 공제 기록 정리', await financeDb.appliedDeductions.count(), 0)

  /**
   * 화면의 세 숫자가 어긋나면 어느 것이 맞는지 알 수 없다.
   *
   * 상환 지분을 순자산에만 더하고 자산 합계에서 빠뜨려 실제로 어긋났다 —
   * "상단 자산과 그래프에 안 보인다"는 보고가 그것이다.
   */
  console.log('\n[17] 자산 − 부채 = 순자산, 그래프에도 나온다')
  const { getNetWorthBreakdown } = await import('../src/finance/db/assets')
  await reset()
  await addCash({ balance: 5_000_000 })
  await financeDb.debts.add({
    id: 'd1',
    name: '사내대출',
    balance: 25_000_000,
    originalAmount: 30_000_000,
    monthlyPayment: 0,
    monthlyPrincipal: 0,
    monthlyInterest: 0,
    countsInDTI: true,
    reflectFrom: '2026-10-01',
    repaidCountsInNetWorth: true,
  } as never)

  const view = await getNetWorthBreakdown()
  check('상환 지분 500만', view.repaidPrincipal, 5_000_000)
  // 현금 500만 + 상환 지분 500만
  check('자산 합계에 포함', view.totalAssets, 10_000_000)
  check(
    '자산 − 부채 = 순자산',
    view.totalAssets - view.totalDebts,
    view.netWorth,
  )
  check('순자산', view.netWorth, -15_000_000)

  const repaidSlice = view.slices.find((slice) =>
    slice.key.startsWith('repaid:'),
  )
  check('그래프 조각 존재', repaidSlice?.total, 5_000_000)
  check('조각 라벨', repaidSlice?.label, '사내대출 상환 지분')

  // 끄면 자산 합계와 그래프에서 함께 사라진다
  await financeDb.debts.update('d1', { repaidCountsInNetWorth: false })
  const off = await getNetWorthBreakdown()
  check('끄면 자산 합계에서 빠짐', off.totalAssets, 5_000_000)
  check(
    '끄면 그래프 조각도 없다',
    off.slices.some((slice) => slice.key.startsWith('repaid:')),
    false,
  )

  console.log(failures === 0 ? '\n전부 통과\n' : `\n${failures}건 실패\n`)
  process.exit(failures === 0 ? 0 : 1)
}

