/**
 * 실효 잔액과 순자산 검증 — spec-finance-v0.12 §5.7, §5.8
 *
 * 실행: npm run check:balances
 *
 * 이중 계산은 오류를 내지 않고 숫자만 틀리게 만든다. 화면으로는
 * "좀 많아 보이네" 수준이라 몇 달 뒤에야 발견된다. 그래서 하네스로 못 박는다.
 *
 * 확인하는 불변식:
 *   1. 연결이 없으면 잔액이 그대로다
 *   2. 기준일 이후 거래만 더한다 (같은 날짜는 더하지 않는다)
 *   3. 거래를 지우면 잔액이 자동으로 돌아간다
 *   4. 잔액을 다시 입력하면 기준일이 리셋되어 이중 계산이 없다
 *   5. 부채는 줄고 0 아래로 내려가지 않는다
 *   6. 고정비 연결이 카테고리 연결보다 우선한다
 *   7. 보증금은 순자산에서 빠지고 제외 합계로 잡힌다
 *   8. countsInNetWorth를 켜면 보증금도 포함된다
 */
import 'fake-indexeddb/auto'

let failures = 0

function check(label: string, actual: unknown, expected: unknown): void {
  const a = JSON.stringify(actual)
  const e = JSON.stringify(expected)
  if (a === e) {
    console.log(`  ok   ${label}`)
  } else {
    failures += 1
    console.log(`  FAIL ${label}\n         기대: ${e}\n         실제: ${a}`)
  }
}

async function main(): Promise<void> {
  const { financeDb } = await import('../src/finance/db/db')
  const { loadBalances } = await import('../src/finance/db/balances')
  const { computeNetWorth, countsInNetWorth } = await import(
    '../src/finance/lib/netWorth'
  )
  const { saveAsset } = await import('../src/finance/db/assets')

  await financeDb.open()

  const reset = async () => {
    await financeDb.assets.clear()
    await financeDb.debts.clear()
    await financeDb.categories.clear()
    await financeDb.transactions.clear()
    await financeDb.fixedCosts.clear()
  }

  const addAsset = (over: Record<string, unknown> = {}) =>
    financeDb.assets.add({
      id: 'a1',
      name: '적금',
      kind: 'SAVINGS',
      balance: 1_000_000,
      updatedAt: 1,
      isLiquidByTarget: true,
      reflectFrom: '2026-10-01',
      ...over,
    } as never)

  const addCategory = (over: Record<string, unknown> = {}) =>
    financeDb.categories.add({
      id: 'c1',
      name: '예적금',
      groupId: 'g1',
      type: 'SAVING',
      budget: 0,
      isFixed: false,
      sortOrder: 0,
      isArchived: false,
      ...over,
    } as never)

  const addTx = (id: string, date: string, amount: number, over = {}) =>
    financeDb.transactions.add({
      id,
      date,
      cycleKey: date.slice(0, 7),
      type: 'SAVING',
      categoryId: 'c1',
      amount,
      isFixed: false,
      isAutoGenerated: false,
      ...over,
    } as never)

  console.log('\n[1] 연결이 없으면 잔액 그대로')
  await reset()
  await addAsset()
  await addCategory() // assetId 없음
  await addTx('t1', '2026-10-10', 500_000)
  let balances = await loadBalances()
  check('잔액 변화 없음', balances.assets[0].balance, 1_000_000)
  check('반영액 0', balances.assets[0].reflected, 0)

  console.log('\n[2] 기준일 이후 거래만 더한다')
  await reset()
  await addAsset({ reflectFrom: '2026-10-10' })
  await addCategory({ assetId: 'a1' })
  await addTx('before', '2026-10-05', 100_000) // 기준일 이전 — 제외
  await addTx('sameday', '2026-10-10', 200_000) // 기준일과 같은 날 — 제외
  await addTx('after', '2026-10-15', 300_000) // 이후 — 포함
  balances = await loadBalances()
  check('이후 거래만 반영', balances.assets[0].reflected, 300_000)
  check('잔액 = 원금 + 반영', balances.assets[0].balance, 1_300_000)

  console.log('\n[3] 거래를 지우면 자동으로 돌아간다')
  await financeDb.transactions.delete('after')
  balances = await loadBalances()
  check('삭제 후 반영액 0', balances.assets[0].reflected, 0)
  check('삭제 후 잔액 복귀', balances.assets[0].balance, 1_000_000)

  console.log('\n[4] 잔액 재입력이 기준일을 리셋한다 — 이중 계산 방지')
  await reset()
  await addAsset({ reflectFrom: '2026-10-01' })
  await addCategory({ assetId: 'a1' })
  await addTx('t1', '2026-10-15', 500_000)
  balances = await loadBalances()
  check('반영 전 잔액', balances.assets[0].balance, 1_500_000)

  // 화면이 보여 준 1,500,000을 그대로 저장한다 (오늘이 기준일이 된다)
  const today = new Date()
  const todayStr = `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(2, '0')}-${String(today.getDate()).padStart(2, '0')}`
  await saveAsset(
    {
      name: '적금',
      kind: 'SAVINGS',
      balance: 1_500_000,
      isLiquidByTarget: true,
    },
    'a1',
  )
  const saved = await financeDb.assets.get('a1')
  check('기준일이 오늘로 리셋', saved?.reflectFrom, todayStr)
  balances = await loadBalances()
  check('재입력 후 이중 계산 없음', balances.assets[0].balance, 1_500_000)
  check('재입력 후 반영액 0', balances.assets[0].reflected, 0)

  console.log('\n[5] 부채는 줄고 0 아래로 안 내려간다')
  await reset()
  await financeDb.debts.add({
    id: 'd1',
    name: '회사대출',
    balance: 1_000_000,
    monthlyPayment: 0,
    monthlyPrincipal: 0,
    monthlyInterest: 0,
    countsInDTI: true,
    reflectFrom: '2026-10-01',
  } as never)
  await addCategory({ debtId: 'd1', type: 'TRANSFER' })
  await addTx('p1', '2026-10-15', 300_000, { type: 'TRANSFER' })
  balances = await loadBalances()
  check('상환 반영', balances.debts[0].reflected, 300_000)
  check('잔액 감소', balances.debts[0].balance, 700_000)

  await addTx('p2', '2026-10-20', 900_000, { type: 'TRANSFER' })
  balances = await loadBalances()
  check('과다 상환도 0에서 멈춤', balances.debts[0].balance, 0)

  console.log('\n[6] 고정비 연결이 카테고리 연결보다 우선')
  await reset()
  await addAsset({ id: 'a1', name: '청약', reflectFrom: '2026-10-01' })
  await financeDb.assets.add({
    id: 'a2',
    name: '적금',
    kind: 'SAVINGS',
    balance: 0,
    updatedAt: 1,
    isLiquidByTarget: true,
    reflectFrom: '2026-10-01',
  } as never)
  await addCategory({ assetId: 'a1' })
  await financeDb.fixedCosts.add({
    id: 'f1',
    categoryId: 'c1',
    amount: 100_000,
    dayOfMonth: 25,
    isActive: true,
    startCycle: '2026-10',
    linkedAssetId: 'a2',
  } as never)
  await addTx('t1', '2026-10-15', 100_000, { fixedCostId: 'f1' })
  balances = await loadBalances()
  const byId = new Map(balances.assets.map((a) => [a.id, a.reflected]))
  check('고정비가 가리킨 자산에 반영', byId.get('a2'), 100_000)
  check('카테고리 자산에는 반영 안 됨', byId.get('a1'), 0)

  console.log('\n[7] 보증금은 순자산에서 빠진다')
  await reset()
  await addAsset({ id: 'a1', name: '적금', kind: 'SAVINGS', balance: 5_000_000 })
  await financeDb.assets.add({
    id: 'a2',
    name: '전세보증금',
    kind: 'DEPOSIT',
    balance: 100_000_000,
    updatedAt: 1,
    isLiquidByTarget: false,
    reflectFrom: '2026-10-01',
  } as never)
  balances = await loadBalances()
  let totals = computeNetWorth(balances.assets, balances.debts)
  check('순자산에 보증금 미포함', totals.netWorth, 5_000_000)
  check('제외 합계로 잡힘', totals.excludedAssets, 100_000_000)
  check(
    'DEPOSIT 기본 제외',
    countsInNetWorth(balances.assets.find((a) => a.id === 'a2')!),
    false,
  )

  console.log('\n[8] countsInNetWorth를 켜면 포함된다')
  await financeDb.assets.update('a2', { countsInNetWorth: true })
  balances = await loadBalances()
  totals = computeNetWorth(balances.assets, balances.debts)
  check('켜면 순자산에 포함', totals.netWorth, 105_000_000)
  check('제외 합계 0', totals.excludedAssets, 0)

  console.log(failures === 0 ? '\n전부 통과\n' : `\n${failures}건 실패\n`)
  process.exit(failures === 0 ? 0 : 1)
}

void main()
